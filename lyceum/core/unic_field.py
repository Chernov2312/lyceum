import re


class Normalise:
    @classmethod
    def normalize(cls, value):
        value = value.lower().strip()
        replacements = {
            'а': 'a',
            'б': 'b',
            'в': 'v',
            'г': 'g',
            'д': 'd',
            'е': 'e',
            'ё': 'yo',
            'ж': 'zh',
            'з': 'z',
            'и': 'i',
            'й': 'y',
            'к': 'k',
            'л': 'l',
            'м': 'm',
            'н': 'n',
            'о': 'o',
            'п': 'p',
            'р': 'r',
            'с': 's',
            'т': 't',
            'у': 'u',
            'ф': 'f',
            'х': 'kh',
            'ц': 'ts',
            'ч': 'ch',
            'ш': 'sh',
            'щ': 'shch',
            'ъ': '',
            'ы': 'y',
            'ь': '',
            'э': 'e',
            'ю': 'yu',
            'я': 'ya',
        }
        for old, new in replacements.items():
            value = value.replace(old, new)
        value = re.sub(r'[^\w\s]', '', value)
        value = re.sub(r'\s+', '', value)
        print('asdfghjkl;', value)
        return value.strip()
